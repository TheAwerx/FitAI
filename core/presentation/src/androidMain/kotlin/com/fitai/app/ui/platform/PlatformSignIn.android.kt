package com.fitai.app.ui.platform

import android.content.Context
import android.util.Log
import androidx.activity.ComponentActivity
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.runtime.rememberCoroutineScope
import androidx.compose.ui.platform.LocalContext
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import fitai.composeapp.generated.resources.Res
import fitai.composeapp.generated.resources.google_web_client_id
import kotlinx.coroutines.launch
import org.jetbrains.compose.resources.stringResource

@Composable
actual fun rememberGoogleSignInLauncher(onToken: (Result<String>) -> Unit): () -> Unit {
    val context = LocalContext.current
    val activity = context as? ComponentActivity
    val scope = rememberCoroutineScope()
    val configuredClientId = stringResource(Res.string.google_web_client_id)
    val serverClientId = remember(context, configuredClientId) {
        configuredClientId.ifBlank { context.defaultWebClientId() }
    }
    return remember(activity, scope, serverClientId, onToken) {
        {
            when {
                serverClientId.isBlank() ->
                    onToken(Result.failure(IllegalStateException("google_client_missing")))
                activity == null ->
                    onToken(Result.failure(IllegalStateException("activity_required")))
                else ->
                    scope.launch {
                        val tokenResult = runCatching {
                            val option = GetGoogleIdOption.Builder()
                                .setServerClientId(serverClientId)
                                .setFilterByAuthorizedAccounts(false)
                                .setAutoSelectEnabled(false)
                                .build()
                            val request = GetCredentialRequest.Builder()
                                .addCredentialOption(option)
                                .build()
                            val credManager = CredentialManager.create(activity)
                            val response = credManager.getCredential(activity, request)
                            val cred = response.credential
                            if (cred is CustomCredential &&
                                cred.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
                            ) {
                                try {
                                    GoogleIdTokenCredential.createFrom(cred.data).idToken
                                } catch (e: GoogleIdTokenParsingException) {
                                    Log.w("FitAI", e)
                                    throw e
                                }
                            } else {
                                error("unexpected_credential")
                            }
                        }
                        onToken(tokenResult)
                    }
            }
        }
    }
}

/** Web client id generated by the google-services plugin from `google-services.json`. */
private fun Context.defaultWebClientId(): String {
    val resId = resources.getIdentifier("default_web_client_id", "string", packageName)
    return if (resId == 0) "" else getString(resId)
}

@Composable
actual fun rememberAppleSignInLauncher(onResult: (Result<Pair<String, String>>) -> Unit): () -> Unit =
    remember(onResult) {
        {
            onResult(Result.failure(IllegalStateException("apple_unsupported_android")))
        }
    }
